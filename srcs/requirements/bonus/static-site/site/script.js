    function snake() {
        const size = 20;
        const cell = 16;
        const canvas = document.createElement("canvas");
        canvas.width = size * cell;
        canvas.height = size * cell;
        canvas.className = "game";
        output.appendChild(canvas);
        const ctx = canvas.getContext("2d");
        const color = themeColor();

        let body = [{ x: 10, y: 10 }];
        let dir = { x: 1, y: 0 };
        let nextDir = dir;
        let score = 0;
        let food = spawn();

        function spawn() {
            let p;
            do {
                p = { x: Math.floor(Math.random() * size), y: Math.floor(Math.random() * size) };
            } while (body.some((s) => s.x === p.x && s.y === p.y));
            return p;
        }

        function draw() {
            ctx.fillStyle = "#000";
            ctx.fillRect(0, 0, canvas.width, canvas.height);
            ctx.fillStyle = color;
            body.forEach((s) => ctx.fillRect(s.x * cell + 1, s.y * cell + 1, cell - 2, cell - 2));
            ctx.fillStyle = "#fff";
            ctx.fillRect(food.x * cell + 3, food.y * cell + 3, cell - 6, cell - 6);
        }

        function end(reason) {
            clearInterval(timer);
            document.removeEventListener("keydown", onKey, true);
            gameRunning = false;
            print(`${reason} Score: ${score}`, "accent");
            scrollDown();
        }

        function step() {
            dir = nextDir;
            const head = { x: body[0].x + dir.x, y: body[0].y + dir.y };
            const outside = head.x < 0 || head.y < 0 || head.x >= size || head.y >= size;
            if (outside || body.some((s) => s.x === head.x && s.y === head.y)) {
                end("Game over.");
                return;
            }
            body.unshift(head);
            if (head.x === food.x && head.y === food.y) {
                score++;
                food = spawn();
            } else {
                body.pop();
            }
            draw();
        }

        function onKey(e) {
            const moves = {
                ArrowUp: [0, -1], ArrowDown: [0, 1], ArrowLeft: [-1, 0], ArrowRight: [1, 0],
                w: [0, -1], z: [0, -1], s: [0, 1], a: [-1, 0], q: [-1, 0], d: [1, 0],
            };
            if (e.key === "Escape") { e.preventDefault(); end("Game quit."); return; }
            // Keep typed characters out of the command line, but leave browser shortcuts alone.
            if (e.key.length === 1 && !e.ctrlKey && !e.metaKey && !e.altKey) e.preventDefault();
            const m = moves[e.key];
            if (!m) return;
            e.preventDefault();
            if (m[0] === -dir.x && m[1] === -dir.y) return;
            nextDir = { x: m[0], y: m[1] };
        }

        document.addEventListener("keydown", onKey, true);
        gameRunning = true;
        print("Arrow keys (or WASD / ZQSD) to play, Esc to quit.", "dim");
        draw();
        const timer = setInterval(step, 110);
        scrollDown();
    }

    function matrix() {
        const canvas = document.createElement("canvas");
        canvas.className = "matrix";
        canvas.width = window.innerWidth;
        canvas.height = window.innerHeight;
        document.body.appendChild(canvas);
        const ctx = canvas.getContext("2d");
        const color = themeColor();
        const fontSize = 16;
        const chars = "アイウエオカキクケコサシスセソタチツテト0123456789ABCDEF";
        const drops = Array.from({ length: Math.floor(canvas.width / fontSize) },
            () => Math.random() * -50);
        let stopped = false;

        const timer = setInterval(() => {
            ctx.fillStyle = "rgba(0, 0, 0, 0.08)";
            ctx.fillRect(0, 0, canvas.width, canvas.height);
            ctx.fillStyle = color;
            ctx.font = `${fontSize}px monospace`;
            drops.forEach((y, i) => {
                const ch = chars[Math.floor(Math.random() * chars.length)];
                ctx.fillText(ch, i * fontSize, y * fontSize);
                drops[i] = y * fontSize > canvas.height && Math.random() > 0.975 ? 0 : y + 1;
            });
        }, 50);

        function stop() {
            if (stopped) return;
            stopped = true;
            clearInterval(timer);
            clearTimeout(auto);
            document.removeEventListener("keydown", stop, true);
            document.removeEventListener("pointerdown", stop, true);
            canvas.remove();
            input.focus();
        }

        const auto = setTimeout(stop, 10000);
        // Ignore the Enter key press that just launched the command.
        setTimeout(() => {
            if (stopped) return;
            document.addEventListener("keydown", stop, true);
            document.addEventListener("pointerdown", stop, true);
        }, 200);
    }

