    // ---------- Execution ----------

    function run(raw) {
        const cmd = raw.trim().replace(/\s+/g, " ");
        const echo = print(`${PROMPT} ${raw}`, "cmd");
        if (!cmd) { echo.remove(); return; }

        history.push(cmd);
        historyIndex = history.length;

        const [name, ...args] = cmd.split(" ");
        const key = name.toLowerCase();
        if (Object.hasOwn(commands, key)) {
            commands[key](args);
        } else {
            print(`${name}: command not found. Type 'help'.`, "err");
        }
        scrollDown();
    }

    // Complete to the longest common prefix, or list the candidates like a shell.
    function complete() {
        const prefix = input.value.toLowerCase();
        if (!prefix) return;
        const matches = completions.filter((c) => c.startsWith(prefix));
        if (!matches.length) return;

        let common = matches[0];
        matches.forEach((m) => {
            while (!m.startsWith(common)) common = common.slice(0, -1);
        });

        if (common.length > prefix.length) {
            input.value = common;
        } else if (matches.length > 1) {
            print(`${PROMPT} ${input.value}`, "cmd");
            print(matches.join("  "), "dim");
            scrollDown();
        }
    }

